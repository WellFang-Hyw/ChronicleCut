POOLS = {"small": TOPICS_ANGLE, "event": TOPICS_EVENT}


def pool_for(mode: str) -> list[str]:
    return POOLS.get(str(mode or "small"), TOPICS_ANGLE)


def pick(seed: int | None = None, is_used=None, mode: str = "small") -> str | None:
    """从选题池里随机挑一个**没用过**的题材。

    is_used(candidate) -> bool 由调用方给（它知道生成记录）；
    池子被挑完了返回 None，由调用方决定怎么办（本项目是让模型出个新题）。
    """
    pool = list(pool_for(mode))
    rng = random.Random(seed)
    rng.shuffle(pool)
    for t in pool:
        if is_used is not None and is_used(t):
            continue
        return t
    return None


