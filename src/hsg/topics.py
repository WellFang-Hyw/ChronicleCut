def propose(cfg, llm, avoid: list[str], mode: str = "small") -> str:
    """让模型出一个没做过的新题材（文本走 DeepSeek，符合项目锁定）。"""
    avoid_txt = "\n".join(f"- {a}" for a in avoid[-80:] if a) or "（还没有做过任何题材）"
    if str(mode) == "event":
        system, user_t = PROPOSE_SYSTEM_EVENT, PROPOSE_USER_EVENT
    else:
        system, user_t = PROPOSE_SYSTEM_SMALL, PROPOSE_USER_SMALL
    try:
        data = llm.chat_json(
            system, user_t.format(avoid=avoid_txt), max_tokens=800, temperature=0.85
        )
        topic = ""
        if isinstance(data, dict):
            topic = str(data.get("topic") or data.get("title") or "").strip()
        elif isinstance(data, str):
            topic = data.strip()
        if topic and len(topic) >= 6:
            return topic
    except Exception as exc:  # noqa: BLE001
        raise RuntimeError(f"让模型出新题材失败：{exc}") from exc
    raise RuntimeError("模型没有给出可用的新题材")
